// Command licences checks that every source file carries the licence header
// and that every Go package linked into keel has a licence in allowed.txt.
// The client's bundled packages are checked by the client build itself.
//
// Files under art/ are art, not code: all rights reserved, outside the AGPL
// (art/README.md). They carry the art header instead.
//
//	go run ./tools/licences
//
// It runs from the repository root.
package main

import (
	"bufio"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"sort"
	"strings"
)

const (
	header      = "SPDX-License-Identifier: AGPL-3.0-only"
	artHeader   = "SPDX-License-Identifier: LicenseRef-All-Rights-Reserved"
	artDir      = "art"
	headerLines = 5 // the header must be within the first lines of a file
	sqlcHeader  = "// Code generated by sqlc. DO NOT EDIT."
	allowedFile = "tools/licences/allowed.txt"
)

// sourceExts are the files that carry the header.
var sourceExts = map[string]bool{
	".go": true, ".ts": true, ".tsx": true, ".css": true, ".html": true, ".grit": true,
}

// artDataExts are data files that carry the art header too, under art/ only:
// a JSON recipe names it in its first field.
var artDataExts = map[string]bool{".json": true}

func main() {
	missing, err := missingHeaders(".")
	if err != nil {
		fail(err)
	}
	if len(missing) > 0 {
		fail(fmt.Errorf("files without %q (under %s/: %q) in their first %d lines:\n  %s",
			header, artDir, artHeader, headerLines, strings.Join(missing, "\n  ")))
	}
	fmt.Println("licences: every source file has the header")

	allowed, err := readAllowed(allowedFile)
	if err != nil {
		fail(err)
	}
	if err := checkByHand(allowed); err != nil {
		fail(err)
	}
	args := []string{"tool", "go-licenses", "check", "./cmd/keel", "--allowed_licenses=" + strings.Join(allowed, ","),
		// The game's own code is AGPL; only what it links from others is checked.
		"--ignore", "github.com/daneelvt/keel-over-the-edge"}
	for _, b := range byHand {
		args = append(args, "--ignore", b.module)
	}
	cmd := exec.CommandContext(context.Background(), "go", args...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		fail(fmt.Errorf("go-licenses: a package linked into keel has a licence outside %s: %w", allowedFile, err))
	}
	fmt.Println("licences: every Go package linked into keel is allowed")
}

// byHand are the modules whose licence go-licenses' classifier cannot
// name, read by hand: each is checked here instead, its licence file the
// one read, by its SHA-256, and its licence among those allowed.
var byHand = []struct {
	module, licence, file, sha256 string
}{
	// MIT No Attribution, which the classifier does not know; linked by the
	// MCP SDK's JSON.
	{"github.com/segmentio/asm", "MIT-0", "LICENSE", "cca993712df289a5958bdef69031a5dac0f951ac15afeb313f9eeea55ed59443"},
}

func checkByHand(allowed []string) error {
	for _, b := range byHand {
		if !slices.Contains(allowed, b.licence) {
			return fmt.Errorf("%s's licence, %s, is not in %s", b.module, b.licence, allowedFile)
		}
		out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", b.module).Output()
		if err != nil {
			return fmt.Errorf("finding %s: %w", b.module, err)
		}
		raw, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(out)), b.file))
		if err != nil {
			return fmt.Errorf("%s's licence: %w", b.module, err)
		}
		if sum := sha256.Sum256(raw); hex.EncodeToString(sum[:]) != b.sha256 {
			return fmt.Errorf("%s's %s is not the one read by hand: read it again, and its SHA-256 into byHand", b.module, b.file)
		}
	}
	return nil
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "licences:", err)
	os.Exit(1)
}

// missingHeaders lists the source files under root without their header:
// the AGPL's, or under art/ the art's.
func missingHeaders(root string) ([]string, error) {
	var missing []string
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", ".dev", "node_modules", "dist", "testdata":
				if p != root {
					return fs.SkipDir
				}
			}
			return nil
		}
		rel, _ := filepath.Rel(root, p)
		rel = filepath.ToSlash(rel)
		inArt := strings.HasPrefix(rel, artDir+"/")
		if !sourceExts[filepath.Ext(p)] && !(inArt && artDataExts[filepath.Ext(p)]) {
			return nil
		}
		want := header
		if inArt {
			want = artHeader
		}
		// sqlc writes the first lines of what it generates itself, and its
		// check fails on a file changed after; the queries it compiles
		// carry the header.
		if gen, err := hasHeader(p, sqlcHeader); err != nil || gen {
			return err
		}
		ok, err := hasHeader(p, want)
		if err != nil {
			return err
		}
		if !ok {
			missing = append(missing, rel)
		}
		return nil
	})
	sort.Strings(missing)
	return missing, err
}

func hasHeader(path, header string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for i := 0; i < headerLines && sc.Scan(); i++ {
		if strings.Contains(sc.Text(), header) {
			return true, nil
		}
	}
	return false, sc.Err()
}

func readAllowed(path string) ([]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var ids []string
	for line := range strings.SplitSeq(string(raw), "\n") {
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		if line = strings.TrimSpace(line); line != "" {
			ids = append(ids, line)
		}
	}
	if len(ids) == 0 {
		return nil, fmt.Errorf("%s lists no licences", path)
	}
	return ids, nil
}
